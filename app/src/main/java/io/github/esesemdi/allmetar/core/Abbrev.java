    static String general(String word) {
        return GENERAL.get(word);
    }

    /** Meaning inside a METAR / TAF remark; falls back to the general list. */
    static String remark(String word) {
        String m = REMARK.get(word);
        return m != null ? m : GENERAL.get(word);
    }

    private static void put(Map<String, String> map, String... pairs) {
        for (int i = 0; i + 1 < pairs.length; i += 2) {
            map.put(pairs[i], pairs[i + 1]);
        }
    }

